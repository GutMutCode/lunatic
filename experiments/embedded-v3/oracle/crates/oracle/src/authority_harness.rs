const OBSERVER_POLL: Duration = Duration::from_millis(2);
const OBSERVER_TIMEOUT: Duration = Duration::from_secs(3);

static NONCE_COUNTER: AtomicU64 = AtomicU64::new(1);

/// Exact generated bytes and identities sent to a candidate.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedAuthorityArtifact {
    pub probe: Probe,
    pub kind: AuthorityProbeKind,
    pub bytes: Vec<u8>,
    pub artifact_sha256: String,
    pub parameter_blob: Vec<u8>,
    pub parameter_sha256: String,
}

/// Maps the generator's closed probe union to the frozen candidate protocol.
pub const fn protocol_kind(probe: Probe) -> AuthorityProbeKind {
    match probe {
        Probe::WasiP1FsRead => AuthorityProbeKind::WasiP1FsRead,
        Probe::WasiP1FsMutate => AuthorityProbeKind::WasiP1FsMutate,
        Probe::LunaticTcp => AuthorityProbeKind::LunaticTcp,
        Probe::LunaticUdp => AuthorityProbeKind::LunaticUdp,
        Probe::LunaticSqliteCreate => AuthorityProbeKind::LunaticSqliteCreate,
        Probe::ExtismHttp => AuthorityProbeKind::ExtismHttp,
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(tag = "effect", rename_all = "snake_case")]
pub enum PositiveObservedEffect {
    WasiRead {
        path: PathBuf,
        nonce_sha256: String,
    },
    WasiMutate {
        target: PathBuf,
        nonce_sha256: String,
    },
    Tcp {
        peer: SocketAddr,
        payload_sha256: String,
    },
    Udp {
        peer: SocketAddr,
        payload_sha256: String,
    },
    Sqlite {
        path: PathBuf,
        table: String,
        value_sha256: String,
    },
    Http {
        peer: SocketAddr,
        method: String,
        target: String,
        body_sha256: String,
        output_sha256: String,
    },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct PositiveControlEvidence {
    pub kind: AuthorityProbeKind,
    pub artifact_sha256: String,
    pub parameter_sha256: String,
    pub suite_parameter_sha256: String,
    pub guest_return: i32,
    pub host_call_sequence: Vec<String>,
    pub observed: PositiveObservedEffect,
}

/// How strongly the portable observer can characterize a denial tail.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum DenialObservationCoverage {
    /// A bound socket records every connect/datagram/request attempt.
    BoundEndpointAttempts,
    /// Polling plus final-state comparison detects ordinary mutations, but is
    /// not an operating-system audit log for arbitrarily short transients.
    PolledDurableState,
    /// A successful read leaves no portable durable signal. Candidate typed
    /// denial and its reviewed host path remain required evidence.
    NoPortableReadAudit,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize)]
pub struct ObserverCounts {
    pub tcp_attempts: u64,
    pub tcp_completed: u64,
    pub udp_datagrams: u64,
    pub http_attempts: u64,
    pub http_completed: u64,
    pub observer_errors: u64,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct DurableSnapshot {
    read_sha256: Option<String>,
    mutate_sha256: Option<String>,
    create_sha256: Option<String>,
    sqlite_exists: bool,
    sqlite_wal_exists: bool,
    sqlite_shm_exists: bool,
}

/// Opaque baseline captured immediately before a candidate authority request.
#[derive(Debug, Clone)]
pub struct DenialBaseline {
    kind: AuthorityProbeKind,
    counts: ObserverCounts,
    durable: DurableSnapshot,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct NoEffectEvidence {
    pub kind: AuthorityProbeKind,
    pub coverage: DenialObservationCoverage,
    pub tail_millis: u64,
    pub before: ObserverCounts,
    pub after: ObserverCounts,
}

/// A denial observer that remains active during candidate execution and the
/// full post-terminal tail.
pub struct DenialWatch {
    baseline: DenialBaseline,
    root: PathBuf,
    parameters: Parameters,
    observers: Arc<Mutex<ObserverState>>,
    stop: Arc<AtomicBool>,
    violation: Arc<Mutex<Option<String>>>,
    thread: Option<JoinHandle<()>>,
}

impl DenialWatch {
    pub fn finish(mut self, tail: Duration) -> Result<NoEffectEvidence> {
        let started = Instant::now();
        while started.elapsed() < tail {
            self.ensure_clean()?;
            thread::sleep(OBSERVER_POLL);
        }
        self.stop.store(true, Ordering::SeqCst);
        if let Some(handle) = self.thread.take() {
            handle
                .join()
                .map_err(|_| anyhow!("authority denial watcher panicked"))?;
        }
        self.ensure_clean()?;
        assert_baseline(
            &self.root,
            &self.parameters,
            &self.observers,
            &self.baseline,
        )?;
        let after = observer_counts(&self.observers)?;
        Ok(NoEffectEvidence {
            kind: self.baseline.kind,
            coverage: denial_coverage(self.baseline.kind),
            tail_millis: u64::try_from(tail.as_millis()).unwrap_or(u64::MAX),
            before: self.baseline.counts,
            after,
        })
    }

    fn ensure_clean(&self) -> Result<()> {
        let violation = self
            .violation
            .lock()
            .map_err(|_| anyhow!("authority denial watcher mutex poisoned"))?;
        if let Some(detail) = violation.as_deref() {
            bail!("authority denial watcher observed an effect: {detail}");
        }
        Ok(())
    }
}

impl Drop for DenialWatch {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::SeqCst);
        if let Some(handle) = self.thread.take() {
            let _ = handle.join();
        }
    }
}

#[derive(Debug, Clone)]
struct TcpObservation {
    peer: SocketAddr,
    payload: Option<Vec<u8>>,
}

#[derive(Debug, Clone)]
struct UdpObservation {
    peer: SocketAddr,
    payload: Vec<u8>,
}

#[derive(Debug, Clone)]
struct HttpObservation {
    peer: SocketAddr,
    method: String,
    target: String,
    headers: BTreeMap<String, String>,
    body: Vec<u8>,
}

#[derive(Debug, Default)]
struct ObserverState {
    tcp: Vec<TcpObservation>,
    udp: Vec<UdpObservation>,
    http: Vec<Option<HttpObservation>>,
    errors: Vec<String>,
}

impl ObserverState {
    fn counts(&self) -> ObserverCounts {
        ObserverCounts {
            tcp_attempts: self.tcp.len() as u64,
            tcp_completed: self
                .tcp
                .iter()
                .filter(|observation| observation.payload.is_some())
                .count() as u64,
            udp_datagrams: self.udp.len() as u64,
            http_attempts: self.http.len() as u64,
            http_completed: self.http.iter().filter(|item| item.is_some()).count() as u64,
            observer_errors: self.errors.len() as u64,
        }
    }
}

/// Owns all positive-control targets and in-process network observers.
pub struct AuthorityHarness {
    root: PathBuf,
    parameters: Parameters,
    suite_parameter_sha256: String,
    observers: Arc<Mutex<ObserverState>>,
    shutdown: Arc<AtomicBool>,
    threads: Vec<JoinHandle<()>>,
}

impl AuthorityHarness {
    /// Creates fresh paths, a fresh nonce, and three already-bound observers.
    pub fn bind(run_root: impl AsRef<Path>) -> Result<Self> {
        Self::bind_with_nonce(run_root, fresh_nonce())
    }

    /// Binds the observer suite to the frozen run-specific nonce.
    pub fn bind_with_nonce(run_root: impl AsRef<Path>, nonce: impl Into<String>) -> Result<Self> {
        let nonce = nonce.into();
        let root = run_root
            .as_ref()
            .join(format!("authority-observer-{nonce}"));
        fs::create_dir_all(&root)
            .with_context(|| format!("create authority observer root {}", root.display()))?;

        let tcp_listener = TcpListener::bind(SocketAddrV4::new(Ipv4Addr::LOCALHOST, 0))
            .context("bind authority TCP observer")?;
        let tcp_port = tcp_listener.local_addr()?.port();
        let udp_socket = UdpSocket::bind(SocketAddrV4::new(Ipv4Addr::LOCALHOST, 0))
            .context("bind authority UDP observer")?;
        let udp_port = udp_socket.local_addr()?.port();
        let http_listener = TcpListener::bind(SocketAddrV4::new(Ipv4Addr::LOCALHOST, 0))
            .context("bind authority HTTP observer")?;
        let http_port = http_listener.local_addr()?.port();

        let parameters = Parameters {
            nonce: nonce.clone(),
            wasi_preopen_fd: 3,
            wasi_read_path: format!("read-{nonce}.txt"),
            wasi_mutate_path: format!("mutate-{nonce}.txt"),
            wasi_create_path: format!("create-{nonce}.txt"),
            sqlite_path: root
                .join(format!("sqlite-{nonce}.sqlite3"))
                .to_string_lossy()
                .into_owned(),
            observer_ipv4: Ipv4Addr::LOCALHOST,
            tcp_port,
            udp_port,
            http_port,
            http_path: format!("/authority/{nonce}"),
        };
        parameters.validate().map_err(|message| anyhow!(message))?;
        let suite_parameter_sha256 =
            sha256_hex(&suite_parameter_blob(&parameters).map_err(|message| anyhow!(message))?);

        let observers = Arc::new(Mutex::new(ObserverState::default()));
        let shutdown = Arc::new(AtomicBool::new(false));
        let threads = vec![
            spawn_tcp_observer(tcp_listener, Arc::clone(&observers), Arc::clone(&shutdown))?,
            spawn_udp_observer(udp_socket, Arc::clone(&observers), Arc::clone(&shutdown))?,
            spawn_http_observer(http_listener, Arc::clone(&observers), Arc::clone(&shutdown))?,
        ];
        let harness = Self {
            root,
            parameters,
            suite_parameter_sha256,
            observers,
            shutdown,
            threads,
        };
        harness.reset_external_targets()?;
        Ok(harness)
    }

    pub fn parameters(&self) -> &Parameters {
        &self.parameters
    }

    pub fn suite_parameter_sha256(&self) -> &str {
        &self.suite_parameter_sha256
    }

    pub fn artifact(&self, probe: Probe) -> Result<GeneratedAuthorityArtifact> {
        let bytes = artifact_bytes(probe, &self.parameters).map_err(|message| anyhow!(message))?;
        let parameter_blob =
            parameter_blob(probe, &self.parameters).map_err(|message| anyhow!(message))?;
        Ok(GeneratedAuthorityArtifact {
            probe,
            kind: protocol_kind(probe),
            artifact_sha256: sha256_hex(&bytes),
            parameter_sha256: sha256_hex(&parameter_blob),
            bytes,
            parameter_blob,
        })
    }

    pub fn artifacts(&self) -> Result<Vec<GeneratedAuthorityArtifact>> {
        Probe::ALL
            .iter()
            .copied()
            .map(|probe| self.artifact(probe))
            .collect()
    }

    pub fn observer_counts(&self) -> ObserverCounts {
        self.observers
            .lock()
            .expect("authority observer mutex poisoned")
            .counts()
    }

    /// Executes the exact generated artifact once under an explicitly
    /// permissive host and requires both guest success and its external effect.
    pub fn run_positive_control(&self, probe: Probe) -> Result<PositiveControlEvidence> {
        self.reset_external_targets()?;
        let artifact = self.artifact(probe)?;
        let before = self.observer_counts();
        let (guest_return, host_call_sequence, extism_output) = if probe == Probe::ExtismHttp {
            let output = run_extism_http(&artifact.bytes, &self.parameters).with_context(|| {
                let state = self
                    .observers
                    .lock()
                    .expect("authority observer mutex poisoned");
                format!(
                    "HTTP observer at client failure: counts={:?}, errors={:?}",
                    state.counts(),
                    state.errors
                )
            })?;
            (0, Vec::new(), Some(output))
        } else {
            let (guest_return, host_calls) =
                run_permissive_wasmtime(probe, &artifact.bytes, &self.root, &self.parameters)?;
            (guest_return, host_calls, None)
        };
        ensure!(
            guest_return == 0,
            "{} positive control returned {guest_return}",
            probe.as_str()
        );
        let observed =
            self.observe_positive_effect(probe, before, &host_call_sequence, extism_output)?;
        Ok(PositiveControlEvidence {
            kind: artifact.kind,
            artifact_sha256: artifact.artifact_sha256,
            parameter_sha256: artifact.parameter_sha256,
            suite_parameter_sha256: self.suite_parameter_sha256.clone(),
            guest_return,
            host_call_sequence,
            observed,
        })
    }

    fn observe_positive_effect(
        &self,
        probe: Probe,
        before: ObserverCounts,
        host_calls: &[String],
        extism_output: Option<Vec<u8>>,
    ) -> Result<PositiveObservedEffect> {
        let nonce = self.parameters.nonce.as_bytes();
        match probe {
            Probe::WasiP1FsRead => {
                ensure!(
                    host_calls == ["wasi.path_open:read", "wasi.fd_read", "wasi.fd_close"],
                    "WASI read host-call sequence differs: {host_calls:?}"
                );
                ensure!(
                    fs::read(self.read_path())? == nonce,
                    "WASI read sentinel changed"
                );
                Ok(PositiveObservedEffect::WasiRead {
                    path: self.read_path(),
                    nonce_sha256: sha256_hex(nonce),
                })
            }
            Probe::WasiP1FsMutate => {
                ensure!(
                    host_calls
                        == [
                            "wasi.path_open:mutate",
                            "wasi.fd_write",
                            "wasi.fd_close",
                            "wasi.path_rename",
                            "wasi.path_unlink_file",
                            "wasi.path_open:create",
                            "wasi.fd_write",
                            "wasi.fd_close",
                        ],
                    "WASI mutation host-call sequence differs: {host_calls:?}"
                );
                ensure!(
                    !self.mutate_path().exists(),
                    "WASI mutation sentinel still exists"
                );
                ensure!(
                    fs::read(self.create_path())? == nonce,
                    "WASI mutation target does not contain the exact nonce"
                );
                Ok(PositiveObservedEffect::WasiMutate {
                    target: self.create_path(),
                    nonce_sha256: sha256_hex(nonce),
                })
            }
            Probe::LunaticTcp => {
                ensure!(
                    host_calls
                        == [
                            "lunatic.tcp_connect",
                            "lunatic.tcp_write_vectored",
                            "lunatic.drop_tcp_stream",
                        ],
                    "Lunatic TCP host-call sequence differs: {host_calls:?}"
                );
                self.wait_for_counts(|counts| counts.tcp_completed == before.tcp_completed + 1)?;
                let state = self
                    .observers
                    .lock()
                    .expect("authority observer mutex poisoned");
                ensure!(
                    state.counts().tcp_attempts == before.tcp_attempts + 1,
                    "TCP positive control made an unexpected number of connections"
                );
                let observation = state
                    .tcp
                    .get(before.tcp_attempts as usize)
                    .ok_or_else(|| anyhow!("missing TCP positive observation"))?;
                let payload = observation
                    .payload
                    .as_ref()
                    .ok_or_else(|| anyhow!("TCP positive observation did not complete"))?;
                ensure!(payload == nonce, "TCP positive payload differs from nonce");
                Ok(PositiveObservedEffect::Tcp {
                    peer: observation.peer,
                    payload_sha256: sha256_hex(payload),
                })
            }
            Probe::LunaticUdp => {
                ensure!(
                    host_calls
                        == [
                            "lunatic.udp_bind",
                            "lunatic.udp_send_to",
                            "lunatic.drop_udp_socket",
                        ],
                    "Lunatic UDP host-call sequence differs: {host_calls:?}"
                );
                self.wait_for_counts(|counts| counts.udp_datagrams == before.udp_datagrams + 1)?;
                let state = self
                    .observers
                    .lock()
                    .expect("authority observer mutex poisoned");
                let observation = state
                    .udp
                    .get(before.udp_datagrams as usize)
                    .ok_or_else(|| anyhow!("missing UDP positive observation"))?;
                ensure!(
                    observation.payload == nonce,
                    "UDP positive payload differs from nonce"
                );
                Ok(PositiveObservedEffect::Udp {
                    peer: observation.peer,
                    payload_sha256: sha256_hex(&observation.payload),
                })
            }
            Probe::LunaticSqliteCreate => {
                ensure!(
                    host_calls
                        == [
                            "lunatic.sqlite.open",
                            "lunatic.sqlite.execute",
                            "lunatic.sqlite.sqlite3_close",
                        ],
                    "Lunatic SQLite host-call sequence differs: {host_calls:?}"
                );
                let table =
                    sqlite_table_name(&self.parameters).map_err(|message| anyhow!(message))?;
                let value = read_sqlite_nonce(&self.sqlite_path(), &table)?;
                ensure!(
                    value.as_bytes() == nonce,
                    "SQLite positive row differs from nonce"
                );
                Ok(PositiveObservedEffect::Sqlite {
                    path: self.sqlite_path(),
                    table,
                    value_sha256: sha256_hex(value.as_bytes()),
                })
            }
            Probe::ExtismHttp => {
                ensure!(
                    host_calls.is_empty(),
                    "Extism positive control unexpectedly used comparison shims"
                );
                self.wait_for_counts(|counts| counts.http_completed == before.http_completed + 1)?;
                let output =
                    extism_output.ok_or_else(|| anyhow!("missing Extism positive output"))?;
                ensure!(
                    output == HTTP_RESPONSE,
                    "Extism output differs from HTTP response"
                );
                let state = self
                    .observers
                    .lock()
                    .expect("authority observer mutex poisoned");
                ensure!(
                    state.counts().http_attempts == before.http_attempts + 1,
                    "Extism positive control made an unexpected number of HTTP requests"
                );
                let observation = state
                    .http
                    .get(before.http_attempts as usize)
                    .and_then(Option::as_ref)
                    .ok_or_else(|| anyhow!("missing HTTP positive observation"))?;
                let expected_target = format!(
                    "{}?nonce={}",
                    self.parameters.http_path, self.parameters.nonce
                );
                ensure!(observation.method == "POST", "Extism HTTP method differs");
                ensure!(
                    observation.target == expected_target,
                    "Extism HTTP target differs"
                );
                ensure!(
                    observation
                        .headers
                        .get("x-authority-nonce")
                        .map(String::as_str)
                        == Some(self.parameters.nonce.as_str()),
                    "Extism HTTP nonce header differs"
                );
                ensure!(
                    observation.body == nonce,
                    "Extism HTTP body differs from nonce"
                );
                Ok(PositiveObservedEffect::Http {
                    peer: observation.peer,
                    method: observation.method.clone(),
                    target: observation.target.clone(),
                    body_sha256: sha256_hex(&observation.body),
                    output_sha256: sha256_hex(&output),
                })
            }
        }
    }

    fn wait_for_counts(&self, condition: impl Fn(ObserverCounts) -> bool) -> Result<()> {
        let deadline = Instant::now() + OBSERVER_TIMEOUT;
        loop {
            let counts = self.observer_counts();
            ensure!(
                counts.observer_errors == 0,
                "authority observer reported an error: {:?}",
                self.observers
                    .lock()
                    .expect("authority observer mutex poisoned")
                    .errors
            );
            if condition(counts) {
                return Ok(());
            }
            ensure!(
                Instant::now() < deadline,
                "authority observer timed out; counts {counts:?}"
            );
            thread::sleep(OBSERVER_POLL);
        }
    }

    /// Restores every durable target to the pre-denial state and captures a
    /// cross-surface baseline. Comparing every surface catches a candidate
    /// accidentally invoking the wrong genuine ABI.
    pub fn prepare_denial(&self, probe: Probe) -> Result<DenialBaseline> {
        self.reset_external_targets()?;
        Ok(DenialBaseline {
            kind: protocol_kind(probe),
            counts: self.observer_counts(),
            durable: self.durable_snapshot()?,
        })
    }

    /// Starts the cross-surface denial observer before the candidate receives
    /// the canary. The returned watch must be finished only after the candidate
    /// terminal so transient effects during invocation remain observable.
    pub fn start_denial_watch(&self, probe: Probe) -> Result<DenialWatch> {
        let baseline = self.prepare_denial(probe)?;
        let root = self.root.clone();
        let parameters = self.parameters.clone();
        let observers = Arc::clone(&self.observers);
        let stop = Arc::new(AtomicBool::new(false));
        let violation = Arc::new(Mutex::new(None));
        let thread_root = root.clone();
        let thread_parameters = parameters.clone();
        let thread_observers = Arc::clone(&observers);
        let thread_baseline = baseline.clone();
        let thread_stop = Arc::clone(&stop);
        let thread_violation = Arc::clone(&violation);
        let (ready_tx, ready_rx) = mpsc::sync_channel(0);
        let watcher = thread::Builder::new()
            .name("embedded-v3-authority-denial".into())
            .spawn(move || {
                let mut first = true;
                while !thread_stop.load(Ordering::SeqCst) {
                    if let Err(error) = assert_baseline(
                        &thread_root,
                        &thread_parameters,
                        &thread_observers,
                        &thread_baseline,
                    ) {
                        if let Ok(mut slot) = thread_violation.lock() {
                            *slot = Some(error.to_string());
                        }
                        if first {
                            let _ = ready_tx.send(());
                        }
                        return;
                    }
                    if first {
                        first = false;
                        if ready_tx.send(()).is_err() {
                            return;
                        }
                    }
                    thread::sleep(OBSERVER_POLL);
                }
            })
            .context("spawn authority denial watcher")?;
        ready_rx
            .recv_timeout(OBSERVER_TIMEOUT)
            .context("authority denial watcher did not become ready")?;
        let watch = DenialWatch {
            baseline,
            root,
            parameters,
            observers,
            stop,
            violation,
            thread: Some(watcher),
        };
        watch.ensure_clean()?;
        Ok(watch)
    }

    /// Watches the denial tail and rejects any endpoint attempt or durable
    /// state deviation. NoPortableReadAudit is intentionally not upgraded to
    /// a claim that an otherwise successful read could have been observed.
    pub fn assert_no_effect_after(
        &self,
        baseline: &DenialBaseline,
        tail: Duration,
    ) -> Result<NoEffectEvidence> {
        let started = Instant::now();
        while started.elapsed() < tail {
            self.assert_matches_baseline(baseline)?;
            thread::sleep(OBSERVER_POLL);
        }
        self.assert_matches_baseline(baseline)?;
        let after = self.observer_counts();
        Ok(NoEffectEvidence {
            kind: baseline.kind,
            coverage: denial_coverage(baseline.kind),
            tail_millis: u64::try_from(tail.as_millis()).unwrap_or(u64::MAX),
            before: baseline.counts,
            after,
        })
    }

    fn assert_matches_baseline(&self, baseline: &DenialBaseline) -> Result<()> {
        assert_baseline(&self.root, &self.parameters, &self.observers, baseline)
    }

    fn reset_external_targets(&self) -> Result<()> {
        fs::write(self.read_path(), self.parameters.nonce.as_bytes())
            .context("write authority read sentinel")?;
        fs::write(self.mutate_path(), INITIAL_MUTATE_SENTINEL)
            .context("write authority mutation sentinel")?;
        remove_if_present(&self.create_path())?;
        remove_if_present(&self.sqlite_path())?;
        remove_if_present(&sqlite_sidecar(&self.sqlite_path(), "-wal"))?;
        remove_if_present(&sqlite_sidecar(&self.sqlite_path(), "-shm"))?;
        Ok(())
    }

    fn durable_snapshot(&self) -> Result<DurableSnapshot> {
        durable_snapshot_at(&self.root, &self.parameters)
    }

    fn read_path(&self) -> PathBuf {
        self.root.join(&self.parameters.wasi_read_path)
    }

    fn mutate_path(&self) -> PathBuf {
        self.root.join(&self.parameters.wasi_mutate_path)
    }

    fn create_path(&self) -> PathBuf {
        self.root.join(&self.parameters.wasi_create_path)
    }

    fn sqlite_path(&self) -> PathBuf {
        PathBuf::from(&self.parameters.sqlite_path)
    }
}

impl Drop for AuthorityHarness {
    fn drop(&mut self) {
        self.shutdown.store(true, Ordering::Release);
        while let Some(handle) = self.threads.pop() {
            let _ = handle.join();
        }
    }
}

fn fresh_nonce() -> String {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    let counter = NONCE_COUNTER.fetch_add(1, Ordering::Relaxed);
    format!("run-{:x}-{now:x}-{counter:x}", std::process::id())
}

fn denial_coverage(kind: AuthorityProbeKind) -> DenialObservationCoverage {
    match kind {
        AuthorityProbeKind::WasiP1FsRead => DenialObservationCoverage::NoPortableReadAudit,
        AuthorityProbeKind::WasiP1FsMutate | AuthorityProbeKind::LunaticSqliteCreate => {
            DenialObservationCoverage::PolledDurableState
        }
        AuthorityProbeKind::LunaticTcp
        | AuthorityProbeKind::LunaticUdp
        | AuthorityProbeKind::ExtismHttp => DenialObservationCoverage::BoundEndpointAttempts,
    }
}

fn observer_counts(observers: &Arc<Mutex<ObserverState>>) -> Result<ObserverCounts> {
    observers
        .lock()
        .map(|state| state.counts())
        .map_err(|_| anyhow!("authority observer mutex poisoned"))
}

fn durable_snapshot_at(root: &Path, parameters: &Parameters) -> Result<DurableSnapshot> {
    let read_path = root.join(&parameters.wasi_read_path);
    let mutate_path = root.join(&parameters.wasi_mutate_path);
    let create_path = root.join(&parameters.wasi_create_path);
    let sqlite_path = PathBuf::from(&parameters.sqlite_path);
    Ok(DurableSnapshot {
        read_sha256: file_sha256_if_present(&read_path)?,
        mutate_sha256: file_sha256_if_present(&mutate_path)?,
        create_sha256: file_sha256_if_present(&create_path)?,
        sqlite_exists: sqlite_path.exists(),
        sqlite_wal_exists: sqlite_sidecar(&sqlite_path, "-wal").exists(),
        sqlite_shm_exists: sqlite_sidecar(&sqlite_path, "-shm").exists(),
    })
}

fn assert_baseline(
    root: &Path,
    parameters: &Parameters,
    observers: &Arc<Mutex<ObserverState>>,
    baseline: &DenialBaseline,
) -> Result<()> {
    let counts = observer_counts(observers)?;
    ensure!(
        counts == baseline.counts,
        "authority denial caused an endpoint attempt or observer error: before {:?}, after {:?}",
        baseline.counts,
        counts
    );
    let durable = durable_snapshot_at(root, parameters)?;
    ensure!(
        durable == baseline.durable,
        "authority denial changed a durable observer target: before {:?}, after {:?}",
        baseline.durable,
        durable
    );
    Ok(())
}

fn remove_if_present(path: &Path) -> Result<()> {
    match fs::remove_file(path) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error).with_context(|| format!("remove {}", path.display())),
    }
}

fn sqlite_sidecar(path: &Path, suffix: &str) -> PathBuf {
    PathBuf::from(format!("{}{}", path.to_string_lossy(), suffix))
}

fn file_sha256_if_present(path: &Path) -> Result<Option<String>> {
    match fs::read(path) {
        Ok(bytes) => Ok(Some(sha256_hex(&bytes))),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error).with_context(|| format!("read {}", path.display())),
    }
}

fn spawn_tcp_observer(
    listener: TcpListener,
    state: Arc<Mutex<ObserverState>>,
    shutdown: Arc<AtomicBool>,
) -> Result<JoinHandle<()>> {
    listener.set_nonblocking(true)?;
    thread::Builder::new()
        .name("authority-tcp-observer".into())
        .spawn(move || {
            while !shutdown.load(Ordering::Acquire) {
                match listener.accept() {
                    Ok((mut stream, peer)) => {
                        let index = {
                            let mut state =
                                state.lock().expect("authority observer mutex poisoned");
                            let index = state.tcp.len();
                            state.tcp.push(TcpObservation {
                                peer,
                                payload: None,
                            });
                            index
                        };
                        if let Err(error) = stream.set_nonblocking(false) {
                            record_observer_error(
                                &state,
                                format!("TCP observer stream setup for {peer} failed: {error}"),
                            );
                            continue;
                        }
                        let _ = stream.set_read_timeout(Some(Duration::from_millis(750)));
                        let mut payload = Vec::new();
                        match stream.read_to_end(&mut payload) {
                            Ok(_) => {
                                state.lock().expect("authority observer mutex poisoned").tcp
                                    [index]
                                    .payload = Some(payload);
                            }
                            Err(error) => record_observer_error(
                                &state,
                                format!("TCP observer read from {peer} failed: {error}"),
                            ),
                        }
                    }
                    Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                        thread::sleep(OBSERVER_POLL)
                    }
                    Err(error) => {
                        record_observer_error(
                            &state,
                            format!("TCP observer accept failed: {error}"),
                        );
                        thread::sleep(OBSERVER_POLL);
                    }
                }
            }
        })
        .context("spawn authority TCP observer")
}

