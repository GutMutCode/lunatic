//! Oracle-owned positive controls and effect observers for the authority gate.
//!
//! The comparison sends the exact generated artifacts returned by this module
//! to candidates. Positive controls execute those bytes in-process with a
//! permissive host. Candidate denial is then checked against observers that
//! were bound before invocation. Pure reads have no portable durable external
//! signal, so that limitation is represented explicitly instead of being
//! silently promoted to proof of non-access.

