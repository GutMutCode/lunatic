function normalizeLf(value) {
  return value.replaceAll("\\r\\n", "\\n");
}

export function generateCandidateWire(oracleSource) {
  let source = normalizeLf(oracleSource);
  const testDoubleStart = source.indexOf(
    "/// Test-double identity is intentionally outside the production candidate set.",
  );
  const envelopeStart = source.indexOf(
    "#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n" +
      "#[serde(deny_unknown_fields)]\n" +
      "pub struct ControlEnvelope",
    testDoubleStart,
  );
  if (testDoubleStart < 0 || envelopeStart < 0) {
    throw new Error("oracle CandidateIdentity boundary changed; update the explicit projection");
  }
  source = source.slice(0, testDoubleStart) + source.slice(envelopeStart);
  source = source.replaceAll("CandidateIdentity", "CandidateKind");
  source = source.replaceAll("crate::wire_bounds::decode_bounded(line)?", "decode_bounded(line)?");
  const decoderStart = source.indexOf("pub fn decode_control_line");
  if (decoderStart < 0) {
    throw new Error("oracle decoder boundary changed");
  }
  source = source.slice(0, decoderStart) + STANDALONE_CODEC + source.slice(decoderStart);
  return GENERATED_HEADER + source.trimEnd() + ENCODERS_AND_TESTS;
}

function sha256(contents) {
  return crypto.createHash("sha256").update(contents).digest("hex");
}

function rustfmtGenerated(contents) {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "embedded-v3-wire-format-"));
  const source = path.join(temporary, "protocol.rs");
  try {
    fs.writeFileSync(source, contents);
    const result = childProcess.spawnSync(
      "rustfmt",
      ["--edition", "2018", source],
      { encoding: "utf8" },
    );
    if (result.error) throw result.error;
    if (result.status !== 0) {
      throw new Error(`rustfmt failed to canonicalize generated wire: ${result.stderr}`);
    }
    return normalizeLf(fs.readFileSync(source, "utf8"));
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
}

function expectedBytes() {
  return rustfmtGenerated(generateCandidateWire(fs.readFileSync(ORACLE_SOURCE, "utf8")));
}

function assertFrozenCopy(expected) {
  const actual = fs.readFileSync(FROZEN_SOURCE, "utf8");
  if (actual.includes("\r")) {
    throw new Error("candidate wire must use LF-only bytes");
  }
  if (actual !== expected) {
    throw new Error(
      "candidate wire drift: regenerate protocol/candidate-wire-frozen.rs from the oracle projection",
    );
  }
}

function run(command, args, options = {}) {
  const result = childProcess.spawnSync(command, args, {
    encoding: "utf8",
    stdio: "inherit",
    ...options,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} exited with status ${result.status}`);
  }
}

function standaloneTest(expected) {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "embedded-v3-candidate-wire-"));
  try {
    fs.mkdirSync(path.join(temporary, "src"));
    fs.writeFileSync(
      path.join(temporary, "Cargo.toml"),
      `[package]
name = "embedded-v3-candidate-wire-check"
version = "0.0.0"
edition = "2018"

[dependencies]
serde = { version = "=1.0.229", default-features = false, features = ["derive", "std"] }
serde_json = { version = "=1.0.151", default-features = false, features = ["std"] }
sha2 = { version = "=0.10.9", default-features = false, features = ["std"] }
`,
    );
    fs.writeFileSync(path.join(temporary, "src", "lib.rs"), expected);
    run("rustfmt", ["--check", "--edition", "2018", path.join(temporary, "src", "lib.rs")]);
    run("cargo", ["test", "--quiet"], { cwd: temporary });
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
}

function chunkPatch(expected, index) {
  const lines = expected.trimEnd().split("\n");
  // Keep each apply_patch argument comfortably below the Windows command-line
  // limit even when a chunk contains long strictness-test literals.
  const chunkSize = 100;
  const chunks = [];
  for (let offset = 0; offset < lines.length; offset += chunkSize) {
    chunks.push(lines.slice(offset, offset + chunkSize));
  }
  if (!Number.isSafeInteger(index) || index < 0 || index >= chunks.length) {
    throw new Error(`chunk index must be in 0..${chunks.length - 1}`);
  }
  const additions = chunks[index].map((line) => `+${line}`).join("\n");
  const patch = `*** Begin Patch
*** Update File: experiments/embedded-v3/protocol/candidate-wire-frozen.rs
@@
-${APPEND_MARKER}
${additions}
+${APPEND_MARKER}
*** End Patch
`;
  process.stdout.write(Buffer.from(patch, "utf8").toString("base64"));
}

export function checkFrozenCandidateWire({ standalone = false } = {}) {
  const expected = expectedBytes();
  assertFrozenCopy(expected);
  if (standalone) standaloneTest(expected);
  return {
    status: "ok",
    generated_copy_sha256: sha256(Buffer.from(expected, "utf8")),
    oracle_source_sha256: sha256(fs.readFileSync(ORACLE_SOURCE)),
    edition: "2018",
  };
}

function main() {
  const expected = expectedBytes();
  if (process.argv[2] === "--chunk-count") {
    process.stdout.write(String(Math.ceil(expected.trimEnd().split("\n").length / 100)));
    return;
  }
  if (process.argv[2] === "--chunk-patch-base64") {
    chunkPatch(expected, Number(process.argv[3]));
    return;
  }
  const result = checkFrozenCandidateWire({
    standalone: process.argv[2] !== "--check-only",
  });
  process.stdout.write(
    JSON.stringify(result, null, 2) + "\n",
  );
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))
) {
  main();
}
