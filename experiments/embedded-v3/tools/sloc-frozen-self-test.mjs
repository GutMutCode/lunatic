function check(condition, message) {
  if (!condition) throw new Error(message);
}

function isWithin(parent, child) {
  const relative = path.relative(parent, child);
  return (
    relative === "" ||
    (!path.isAbsolute(relative) && relative !== ".." && !relative.startsWith(`..${path.sep}`))
  );
}

function canonicalEntry() {
  const [canonicalId, canonical] = [...CANONICAL_EXCLUSIONS.entries()][0];
  return {
    path: canonical.destination,
    role: "generated",
    category: canonical.category,
    reason: canonical.reason,
    generator: canonical.generator,
    source: canonical.source,
    generated_kind: "canonical-copy",
    canonical_id: canonicalId,
    sha256: canonical.sha256,
  };
}

function fixtureEntries() {
  return [
    { role: "lockfile", ...LOCKFILE_METADATA },
    { path: "Cargo.toml", role: "production", category: "build-configuration" },
    { ...ACCOUNTING_METADATA, role: "accounting" },
    canonicalEntry(),
    { path: "src/lib.rs", role: "production", category: "host" },
    { path: "tests/smoke.rs", role: "test", category: "test" },
  ];
}

function writeManifest(root, candidate, entries) {
  fs.writeFileSync(
    path.join(root, "sloc-manifest.json"),
    `${JSON.stringify({ schema_version: 3, candidate, entries }, null, 2)}\n`,
  );
}

function createFixture(root, candidate = "lunatic") {
  fs.mkdirSync(path.join(root, "src"), { recursive: true });
  fs.mkdirSync(path.join(root, "tests"), { recursive: true });
  fs.copyFileSync(
    path.join(EXPERIMENT_ROOT, "protocol", "candidate-wire-frozen.rs"),
    path.join(root, "src", "protocol.rs"),
  );
  fs.writeFileSync(
    path.join(root, "Cargo.toml"),
    '[package]\nname = "embedded-v3-sloc-fixture"\nversion = "0.0.0"\nedition = "2018"\n',
  );
  fs.writeFileSync(
    path.join(root, "Cargo.lock"),
    '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "embedded-v3-sloc-fixture"\nversion = "0.0.0"\n',
  );
  fs.writeFileSync(path.join(root, "src", "lib.rs"), "// Comments count as physical SLOC.\n\npub fn fixture() {}\n");
  fs.writeFileSync(path.join(root, "tests", "smoke.rs"), "// Test comments count too.\n#[test]\nfn smoke() {}\n");
  writeManifest(root, candidate, fixtureEntries());
}

function replaceManifestAndGenerateLock(root, manifest) {
  fs.writeFileSync(path.join(root, "Cargo.toml"), manifest);
  fs.rmSync(path.join(root, "Cargo.lock"));
  const result = childProcess.spawnSync(
    "cargo",
    ["generate-lockfile", "--offline", "--manifest-path", path.join(root, "Cargo.toml")],
    {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 16 * 1024 * 1024,
      windowsHide: true,
    },
  );
  if (result.error) throw new Error(`cargo generate-lockfile --offline could not run: ${result.error.message}`);
  check(
    result.status === 0,
    `cargo generate-lockfile --offline failed: ${(result.stderr || result.stdout).trim()}`,
  );
}

function readFixtureManifest(root) {
  return JSON.parse(fs.readFileSync(path.join(root, "sloc-manifest.json"), "utf8"));
}

function rewriteFixtureManifest(root, mutator) {
  const manifest = readFixtureManifest(root);
  mutator(manifest);
  writeManifest(root, manifest.candidate, manifest.entries);
}

function binaryGuestEntry(contents, overrides = {}) {
  return {
    path: "guest-artifacts/core.wasm",
    role: "generated",
    category: BINARY_GUEST_METADATA.category,
    reason: BINARY_GUEST_METADATA.reason,
    generator: "fixture-wasm-builder",
    source: "candidate:src/lib.rs",
    generated_kind: "binary-guest",
    sha256: sha256(contents),
    ...overrides,
  };
}

function expectFailure(label, operation, pattern) {
  let caught = null;
  try {
    operation();
  } catch (error) {
    caught = error;
  }
  check(caught !== null, `${label}: expected failure but analysis succeeded`);
  check(pattern.test(caught.message), `${label}: unexpected error: ${caught.message}`);
}

function registryDeclaration(name, specification, overrides = {}) {
  return {
    name,
    source: specification.source,
    req: specification.requirement,
    kind: null,
    rename: null,
    optional: false,
    uses_default_features: specification.default_features,
    features: [...specification.features],
    target: null,
    registry: null,
    path: null,
    ...overrides,
  };
}

function syntheticMetadata(dependencies) {
  const root = {
    id: "path+file:///candidate#embedded-v3-sloc-fixture@0.0.0",
    name: "embedded-v3-sloc-fixture",
    version: "0.0.0",
    source: null,
    dependencies,
  };
  const packages = [root];
  const deps = [];
  for (const dependency of dependencies) {
    const version = dependency.req.startsWith("=") ? dependency.req.slice(1) : "0.0.0";
    const id = dependency.path === null
      ? `${dependency.source}#${dependency.name}@${version}`
      : `path+file:///${dependency.name}#${version}`;
    packages.push({
      id,
      name: dependency.name,
      version,
      source: dependency.source,
      manifest_path: dependency.path === null
        ? `C:/cargo/registry/${dependency.name}/Cargo.toml`
        : path.join(dependency.path, "Cargo.toml"),
    });
    deps.push({
      name: dependency.rename ?? dependency.name.replaceAll("-", "_"),
      pkg: id,
      dep_kinds: [{ kind: dependency.kind, target: dependency.target }],
    });
  }
  return {
    root,
    metadata: {
      packages,
      resolve: {
        nodes: [{ id: root.id, deps }],
      },
    },
  };
}

function validateSyntheticDependencies(candidate, candidateRoot, dependencies) {
  const { root, metadata } = syntheticMetadata(dependencies);
  return validateFrozenDirectDependencies(candidate, root, metadata, candidateRoot);
}

